package com.octagens.api;

import com.octagens.api.model.EnergyInfo;
import com.octagens.api.model.GeneratorInfo;
import org.bukkit.Location;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

/**
 * Public entry point of the OctaGens API.
 * <pre>{@code
 * OctaGensAPI api = OctaGensAPI.get();
 * double efficiency = api.getAverageEfficiency(player.getUniqueId());
 * }</pre>
 * All methods must be called from the server main thread.
 */
public interface OctaGensAPI {

    /** Value returned by limit methods when the player has unlimited slots. */
    int UNLIMITED = Integer.MAX_VALUE;

    /**
     * @return the active API instance
     * @throws IllegalStateException if OctaGens is not enabled
     */
    static OctaGensAPI get() {
        OctaGensAPI api = OctaGensAPIHolder.instance;
        if (api == null) {
            throw new IllegalStateException("OctaGens is not enabled");
        }
        return api;
    }

    /** @return true when OctaGens is enabled and the API can be used */
    static boolean isAvailable() {
        return OctaGensAPIHolder.instance != null;
    }

    /** Internal: called by the plugin on enable. Do not call from other plugins. */
    static void register(OctaGensAPI api) {
        OctaGensAPIHolder.instance = api;
    }

    /** Internal: called by the plugin on disable. Do not call from other plugins. */
    static void unregister() {
        OctaGensAPIHolder.instance = null;
    }

    /** @return all generators placed by the given owner (immutable snapshot) */
    List<GeneratorInfo> getGenerators(UUID owner);

    /** @return all energy blocks placed by the given owner (immutable snapshot) */
    List<EnergyInfo> getEnergies(UUID owner);

    /** @return the generator at the given block location, if any */
    Optional<GeneratorInfo> getGeneratorAt(Location location);

    /** @return the energy block at the given block location, if any */
    Optional<EnergyInfo> getEnergyAt(Location location);

    /** @return the sum of Mcu/s of every energy block the owner has placed (= regeneration rate) */
    double getTotalMagicule(UUID owner);

    /** @return Mcu/s generated by energy blocks of the owner that are in range of the given generator */
    double getSupply(GeneratorInfo generator);

    /**
     * @return readiness of the generator from 0.0 to 1.0: owner's current Mcu divided by the Mcu the
     * generator needs per drop (0.0 when no energy block is in range)
     */
    double getEfficiency(GeneratorInfo generator);

    /** @return the owner's current stored Magicule (Mcu) */
    double getMcuCurrent(UUID owner);

    /** @return the owner's maximum Magicule capacity (Mcu) */
    double getMcuMax(UUID owner);

    /** @return the owner's Mcu regeneration per second (sum of all placed energy blocks) */
    double getMcuRegen(UUID owner);

    /** @return average efficiency of all generators of the owner (1.0 if none) */
    double getAverageEfficiency(UUID owner);

    /** @return generator slot limit (defaults + permissions + bonus), {@link #UNLIMITED} if unlimited */
    int getGeneratorLimit(UUID owner);

    /** @return energy slot limit (defaults + permissions + bonus), {@link #UNLIMITED} if unlimited */
    int getEnergyLimit(UUID owner);

    /** @return the number of bonus generator slots granted via API/commands */
    int getBonusGeneratorSlots(UUID owner);

    /** @return the number of bonus energy slots granted via API/commands */
    int getBonusEnergySlots(UUID owner);

    /** Adds bonus generator slots (stored in database). */
    void addGeneratorSlots(UUID owner, int amount);

    /** Removes bonus generator slots (never below zero). */
    void removeGeneratorSlots(UUID owner, int amount);

    /** Adds bonus energy slots (stored in database). */
    void addEnergySlots(UUID owner, int amount);

    /** Removes bonus energy slots (never below zero). */
    void removeEnergySlots(UUID owner, int amount);

    /** @return true while the weekend bonus window is active */
    boolean isWeekendBonusActive();

    /** @return the current drop multiplier from weekend + manual bonus (1.0 if none active) */
    double getWeekendMultiplier();

    /** @return remaining seconds of the weekend window, 0 if inactive */
    long getWeekendRemainingSeconds();
}
